// tinyCSV is a cut-down airports.csv with obviously fake airports: two good
// rows (out of code order), one with no IATA code, a closed one, one whose
// coordinates give no zone, one with bad coordinates and a duplicate code.
const tinyCSV = `"id","ident","type","name","latitude_deg","longitude_deg","municipality","iata_code"
1,"XXZZ","large_airport","Test Zulu Airport",51.5,-0.1,"Testford","XZZ"
2,"XXAA","medium_airport","Test Alpha Airport",35.7,139.7,"Testville","xaa"
3,"XXNO","small_airport","Test No Code Airport",10,10,"Nowhere",""
4,"XXCL","closed","Test Closed Airport",10,10,"Nowhere","XCL"
5,"XXSE","small_airport","Test Sea Airport",0,-30,"Nowhere","XSE"
6,"XXBD","small_airport","Test Bad Airport","north",10,"Nowhere","XBD"
7,"XXDU","small_airport","Test Duplicate Airport",51.5,-0.1,"Elsewhere","XZZ"
`

// fakeZones stands in for geotz: London for the first row, Tokyo for the
// second, nothing at sea.
func fakeZones(lat, lon float64) (string, bool) {
	switch {
	case lat == 51.5:
		return "Europe/London", true
	case lat == 35.7:
		return "Asia/Tokyo", true
	}
	return "", false
}

// tinyCities is a cut-down mwgg airports.json: XZZ's city is the same
// airport, XAA's is a different airport 100 km away, and two rows are unusable.
const tinyCities = `{
 "XXZZ": {"iata": "XZZ", "city": "Test City", "lat": 51.51, "lon": -0.1},
 "XXAA": {"iata": "XAA", "city": "Wrong City", "lat": 36.6, "lon": 139.7},
 "XXNC": {"iata": "XNC", "city": "", "lat": 0, "lon": 0},
 "XXNI": {"iata": "", "city": "No Code City", "lat": 0, "lon": 0}
}`

func tinyCityMap(t *testing.T) map[string]city {
	t.Helper()
	c, err := readCities(strings.NewReader(tinyCities))
	if err != nil {
		t.Fatalf("readCities: %v", err)
	}
	return c
}

func TestReadCities(t *testing.T) {
	c := tinyCityMap(t)
	if len(c) != 2 || c["XZZ"].City != "Test City" {
		t.Errorf("readCities = %+v, want XZZ and XAA only", c)
	}
	if _, err := readCities(strings.NewReader("not json")); err == nil {
		t.Error("bad JSON should fail")
	}
}

func TestShortName(t *testing.T) {
	for in, want := range map[string]string{
		"Test Zulu Airport":           "Test Zulu",
		" Test Airport ":              "Test",
		"Airport":                     "Airport",
		"Test Airport Hotel Heliport": "Test Airport Hotel Heliport",
	} {
		if got := shortName(in); got != want {
			t.Errorf("shortName(%q) = %q, want %q", in, got, want)
		}
	}
}

func TestGenerate(t *testing.T) {
	var skipped bytes.Buffer
	out, err := generate(strings.NewReader(tinyCSV), tinyCityMap(t), fakeZones, &skipped)
	if err != nil {
		t.Fatalf("generate: %v", err)
	}
	src := string(out)
	for _, want := range []string{
		"// Code generated by cmd/gen-airports from OurAirports airports.csv and mwgg airports.json; DO NOT EDIT.",
		"package airports",
		`"XAA": {35.7, 139.7, "Test Alpha", "Asia/Tokyo", "Testville"},`,
		`"XZZ": {51.5, -0.1, "Test Zulu", "Europe/London", "Test City"},`,
		`"TXL": {52.5597, 13.2877, "Berlin Tegel", "Europe/Berlin", "Berlin"},`,
	} {
		if !strings.Contains(src, want) {
			t.Errorf("output lacks %q:\n%s", want, src)
		}
	}
	for _, gone := range []string{"XCL", "XSE", "XBD", "No Code", "Duplicate"} {
		if strings.Contains(src, gone) {
			t.Errorf("output has %q, which should have been skipped:\n%s", gone, src)
		}
	}
	if strings.Index(src, `"XAA"`) > strings.Index(src, `"XZZ"`) {
		t.Errorf("entries are not sorted:\n%s", src)
	}
	for _, want := range []string{"skipped XSE: no zone", "skipped XBD: bad coordinates", "skipped XZZ: duplicate code"} {
		if !strings.Contains(skipped.String(), want) {
			t.Errorf("skipped report lacks %q:\n%s", want, skipped.String())
		}
	}
}

func TestGenerateRejectsInvalidZone(t *testing.T) {
	var skipped bytes.Buffer
	bogus := func(float64, float64) (string, bool) { return "Not/AZone", true }
	if _, err := generate(strings.NewReader(tinyCSV), nil, bogus, &skipped); err == nil {
		t.Error("a table with no valid zones should fail")
	}
	if !strings.Contains(skipped.String(), "skipped XZZ: no zone") {
		t.Errorf("an invalid zone was not reported:\n%s", skipped.String())
	}
}

func TestGenerateFixes(t *testing.T) {
	csv := `"type","name","latitude_deg","longitude_deg","municipality","iata_code"
"large_airport","Test Hanoi Airport",21.2,105.8,"Testville","HAN"
"large_airport","Test Istanbul Airport",41.3,28.7,"Test Suburb","IST"
`
	bangkok := func(float64, float64) (string, bool) { return "Asia/Bangkok", true }
	out, err := generate(strings.NewReader(csv), nil, bangkok, io.Discard)
	if err != nil {
		t.Fatalf("generate: %v", err)
	}
	if !strings.Contains(string(out), `"Asia/Ho_Chi_Minh", "Testville"`) {
		t.Errorf("HAN zone not corrected:\n%s", out)
	}
	if !strings.Contains(string(out), `"Asia/Bangkok", "Istanbul"`) {
		t.Errorf("IST city not corrected:\n%s", out)
	}
}

func TestGenerateErrors(t *testing.T) {
	var skipped bytes.Buffer
	if _, err := generate(strings.NewReader(""), nil, fakeZones, &skipped); err == nil {
		t.Error("an empty file should fail")
	}
	if _, err := generate(strings.NewReader("\"name\",\"iata_code\"\n"), nil, fakeZones, &skipped); err == nil {
		t.Error("missing columns should fail")
	}
	header := `"type","name","latitude_deg","longitude_deg","municipality","iata_code"` + "\n"
	if _, err := generate(strings.NewReader(header), nil, fakeZones, &skipped); err == nil {
		t.Error("no rows should fail")
	}
	if _, err := generate(strings.NewReader(header+"\"a\",\"b\"\n"), nil, fakeZones, &skipped); err == nil {
		t.Error("a short row should fail")
	}
}

func TestRun(t *testing.T) {
	dir := t.TempDir()
	in := filepath.Join(dir, "airports.csv")
	if err := os.WriteFile(in, []byte(tinyCSV), 0o644); err != nil {
		t.Fatal(err)
	}
	cities := filepath.Join(dir, "airports.json")
	if err := os.WriteFile(cities, []byte(tinyCities), 0o644); err != nil {
		t.Fatal(err)
	}
	var stderr bytes.Buffer
	if err := run([]string{"-in", in, "-cities", cities, "-out", filepath.Join(dir, "missing", "x.go")}, &stderr); err == nil {
		t.Error("an unwritable -out should fail")
	}
	out := filepath.Join(dir, "table_gen.go")
	if err := run([]string{"-in", in, "-cities", cities, "-out", out}, &stderr); err != nil {
		t.Fatalf("run: %v", err)
	}
	if _, err := os.Stat(out); err != nil {
		t.Errorf("no output written: %v", err)
	}
	if err := run(nil, &stderr); err == nil {
		t.Error("missing flags should fail")
	}
	if err := run([]string{"-bogus"}, &stderr); err == nil {
		t.Error("an unknown flag should fail")
	}
	if err := run([]string{"-in", filepath.Join(dir, "nope.csv"), "-cities", cities, "-out", out}, &stderr); err == nil {
		t.Error("a missing -in should fail")
	}
	bad := filepath.Join(dir, "bad.csv")
	if err := os.WriteFile(bad, nil, 0o644); err != nil {
		t.Fatal(err)
	}
	if err := run([]string{"-in", bad, "-cities", cities, "-out", out}, &stderr); err == nil {
		t.Error("an empty -in should fail")
	}
	if err := run([]string{"-in", in, "-cities", filepath.Join(dir, "nope.json"), "-out", out}, &stderr); err == nil {
		t.Error("a missing -cities should fail")
	}
	if err := run([]string{"-in", in, "-cities", bad, "-out", out}, &stderr); err == nil {
		t.Error("an empty -cities should fail")
	}
}
