// Command gen-windows-zones writes internal/importics/windowszones_gen.go, the
// table that maps Windows time zone names (as Outlook and Exchange put in a
// TZID, e.g. "W. Europe Standard Time") to IANA zone names.
//
// The source is CLDR's windowsZones.xml, read from a local file so that
// neither the build nor the tests touch the network. To regenerate:
//
//	curl -s -o /tmp/windowsZones.xml https://raw.githubusercontent.com/unicode-org/cldr/main/common/supplemental/windowsZones.xml
//	go run ./cmd/gen-windows-zones -in /tmp/windowsZones.xml -out internal/importics/windowszones_gen.go
//
// Only the territory "001" mappings are kept: those are CLDR's default IANA
// zone for each Windows name, and a TZID carries no territory to pick a
// regional one by.
package main

import (
	"bytes"
	"encoding/xml"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"io"
	"os"
	"sort"
	"strings"
)

func main() {
	if err := run(os.Args[1:], os.Stderr); err != nil {
		fmt.Fprintln(os.Stderr, "gen-windows-zones:", err)
		os.Exit(1)
	}
}

// run parses the flags, generates the table from -in and writes it to -out.
func run(args []string, stderr io.Writer) error {
	fs := flag.NewFlagSet("gen-windows-zones", flag.ContinueOnError)
	fs.SetOutput(stderr)
	in := fs.String("in", "", "path to CLDR windowsZones.xml")
	out := fs.String("out", "", "path of the Go file to write")
	if err := fs.Parse(args); err != nil {
		return err
	}
	if *in == "" || *out == "" {
		return errors.New("both -in and -out are required")
	}
	f, err := os.Open(*in)
	if err != nil {
		return err
	}
	defer f.Close()
	src, err := generate(f)
	if err != nil {
		return fmt.Errorf("%s: %w", *in, err)
	}
	return os.WriteFile(*out, src, 0o644)
}

// supplementalData is the part of windowsZones.xml the table needs.
type supplementalData struct {
	MapTimezones struct {
		OtherVersion string `xml:"otherVersion,attr"`
		TypeVersion  string `xml:"typeVersion,attr"`
		MapZones     []struct {
			Other     string `xml:"other,attr"`
			Territory string `xml:"territory,attr"`
			Type      string `xml:"type,attr"`
		} `xml:"mapZone"`
	} `xml:"windowsZones>mapTimezones"`
}

// generate reads windowsZones.xml and returns the formatted Go source of the
// table, sorted by Windows name so a regeneration gives a stable diff.
func generate(r io.Reader) ([]byte, error) {
	var d supplementalData
	if err := xml.NewDecoder(r).Decode(&d); err != nil {
		return nil, fmt.Errorf("decode windowsZones.xml: %w", err)
	}
	zones := map[string]string{}
	for _, z := range d.MapTimezones.MapZones {
		if z.Territory != "001" {
			continue
		}
		// A type can list several IANA names; the first is the canonical one.
		if fields := strings.Fields(z.Type); len(fields) > 0 && z.Other != "" {
			zones[z.Other] = fields[0]
		}
	}
	if len(zones) == 0 {
		return nil, errors.New("no territory 001 mappings found")
	}
	names := make([]string, 0, len(zones))
	for n := range zones {
		names = append(names, n)
	}
	sort.Strings(names)

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by cmd/gen-windows-zones from CLDR windowsZones.xml (typeVersion %s, otherVersion %s); DO NOT EDIT.\n\n",
		d.MapTimezones.TypeVersion, d.MapTimezones.OtherVersion)
	b.WriteString("package importics\n\n")
	b.WriteString("// windowsZones maps a Windows time zone name to CLDR's default (territory\n")
	b.WriteString("// 001) IANA zone for it.\n")
	b.WriteString("var windowsZones = map[string]string{\n")
	for _, n := range names {
		fmt.Fprintf(&b, "\t%q: %q,\n", n, zones[n])
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}
