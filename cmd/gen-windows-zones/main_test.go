package main

import (
	"io"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// tinyXML is a cut-down windowsZones.xml: two zones with a territory 001
// default, one regional mapping that must be ignored, and a 001 entry whose
// type lists more than one IANA name (only the first is kept).
const tinyXML = `<?xml version="1.0" encoding="UTF-8" ?>
<supplementalData>
	<version number="$Revision$"/>
	<windowsZones>
		<mapTimezones otherVersion="7e11800" typeVersion="2021a">
			<mapZone other="W. Europe Standard Time" territory="001" type="Europe/Berlin"/>
			<mapZone other="W. Europe Standard Time" territory="NL" type="Europe/Amsterdam"/>
			<mapZone other="AUS Eastern Standard Time" territory="001" type="Australia/Sydney Australia/Melbourne"/>
		</mapTimezones>
	</windowsZones>
</supplementalData>
`

func TestGenerate(t *testing.T) {
	out, err := generate(strings.NewReader(tinyXML))
	if err != nil {
		t.Fatalf("generate: %v", err)
	}
	src := string(out)
	for _, want := range []string{
		"// Code generated by cmd/gen-windows-zones from CLDR windowsZones.xml (typeVersion 2021a, otherVersion 7e11800); DO NOT EDIT.",
		"package importics",
		`"W. Europe Standard Time":   "Europe/Berlin",`,
		`"AUS Eastern Standard Time": "Australia/Sydney",`,
	} {
		if !strings.Contains(src, want) {
			t.Errorf("output lacks %q:\n%s", want, src)
		}
	}
	if strings.Contains(src, "Amsterdam") {
		t.Errorf("a regional mapping leaked into the output:\n%s", src)
	}
	// Sorted by Windows name, so regeneration gives a stable diff.
	if strings.Index(src, "AUS Eastern") > strings.Index(src, "W. Europe") {
		t.Errorf("entries are not sorted:\n%s", src)
	}
}

func TestGenerateErrors(t *testing.T) {
	if _, err := generate(strings.NewReader("<not xml")); err == nil {
		t.Error("malformed XML should fail")
	}
	empty := `<supplementalData><windowsZones><mapTimezones/></windowsZones></supplementalData>`
	if _, err := generate(strings.NewReader(empty)); err == nil {
		t.Error("a file with no territory 001 mappings should fail")
	}
}

func TestRun(t *testing.T) {
	dir := t.TempDir()
	in := filepath.Join(dir, "windowsZones.xml")
	out := filepath.Join(dir, "windowszones_gen.go")
	if err := os.WriteFile(in, []byte(tinyXML), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := run([]string{"-in", in, "-out", out}, io.Discard); err != nil {
		t.Fatalf("run: %v", err)
	}
	got, err := os.ReadFile(out)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(got), `"Europe/Berlin"`) {
		t.Errorf("written file lacks the mapping:\n%s", got)
	}
}

func TestRunErrors(t *testing.T) {
	dir := t.TempDir()
	bad := filepath.Join(dir, "bad.xml")
	if err := os.WriteFile(bad, []byte("<not xml"), 0o600); err != nil {
		t.Fatal(err)
	}
	good := filepath.Join(dir, "good.xml")
	if err := os.WriteFile(good, []byte(tinyXML), 0o600); err != nil {
		t.Fatal(err)
	}
	cases := map[string][]string{
		"missing flags":  {},
		"unknown flag":   {"-nope"},
		"missing input":  {"-in", filepath.Join(dir, "absent.xml"), "-out", filepath.Join(dir, "x.go")},
		"bad input":      {"-in", bad, "-out", filepath.Join(dir, "x.go")},
		"unwritable out": {"-in", good, "-out", filepath.Join(dir, "no", "such", "dir", "x.go")},
	}
	for name, args := range cases {
		if err := run(args, io.Discard); err == nil {
			t.Errorf("%s: run(%q) should fail", name, args)
		}
	}
}
